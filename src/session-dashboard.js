function defaultOpenBrowser(targetPath) {
  execFile('cmd.exe', ['/c', 'start', '', targetPath]);
}

function main(argv, options = {}) {
  const { quiet, hide, unhide, rename, handleUri, registerProtocol, unregisterProtocol } = parseArgs(argv);
  const homeDir = os.homedir();
  const claudeHomeDir = options.claudeHomeDir || path.join(homeDir, '.claude');
  const codexHomeDir = options.codexHomeDir || path.join(homeDir, '.codex');
  const openBrowser = options.openBrowser || defaultOpenBrowser;
  const hiddenListPath = options.hiddenListPath || path.join(claudeHomeDir, HIDDEN_LIST_FILENAME);
  const protocolTokenPath = options.protocolTokenPath || path.join(claudeHomeDir, PROTOCOL_TOKEN_FILENAME);
  const protocolLogPath = options.protocolLogPath || path.join(claudeHomeDir, PROTOCOL_LOG_FILENAME);
  const protocolScriptPath = options.protocolScriptPath || path.join(homeDir, '.claude', 'scripts', 'session-dashboard.js');
  const execProtocolCommand = options.execProtocolCommand || defaultExecProtocolCommand;
  const spawnResumeFn = options.spawnResumeFn || spawn;

  // --register-protocol/--unregister-protocol are one-time system-setup actions, not "scan and
  // maybe hide/rename" actions — they short-circuit before any scanning/HTML-writing/browser-
  // opening happens, and take priority over any other flag passed alongside them.
  if (registerProtocol) {
    registerProtocolHandler(execProtocolCommand, protocolScriptPath);
    return { registered: true };
  }
  if (unregisterProtocol) {
    unregisterProtocolHandler(execProtocolCommand);
    return { unregistered: true };
  }

  // --handle-uri must fully validate before touching hideSession/renameSession — a rejection
  // throws immediately and never falls through to the normal scan/build/write flow below.
  if (handleUri) {
    handleProtocolUri(handleUri, { claudeHomeDir, codexHomeDir, hiddenListPath, tokenPath: protocolTokenPath, logPath: protocolLogPath, spawnFn: spawnResumeFn });
  }

  hide.forEach((h) => hideSession(hiddenListPath, h.tool, h.id));
  unhide.forEach((u) => unhideSession(hiddenListPath, u.tool, u.id));
  if (rename) renameSession(claudeHomeDir, codexHomeDir, rename.tool, rename.id, rename.title);

  const claudeResult = scanClaudeCode(claudeHomeDir, homeDir);
  const codexResult = scanCodex(codexHomeDir, homeDir);
  const deduped = dedupeSessions([...claudeResult.sessions, ...codexResult.sessions]);
  const hiddenList = loadHiddenList(hiddenListPath);
  const sessions = filterHiddenSessions(deduped, hiddenList);
  const skippedCount = claudeResult.skipped + codexResult.skipped;
  const skippedDetails = [...claudeResult.skippedDetails, ...codexResult.skippedDetails];
  const protocolToken = loadOrCreateProtocolToken(protocolTokenPath);

  const html = buildHtml(sessions, { generatedAt: new Date().toISOString(), skippedCount, skippedDetails, protocolToken });
  const targetPath = path.join(claudeHomeDir, 'sessions-dashboard.html');
  writeAtomic(targetPath, html);

  // --hide/--unhide/--rename/--handle-uri are scripted maintenance actions invoked via a copied
  // CLI command or protocol link (see the hide/rename buttons in buildHtml) — they never open
  // the browser, regardless of --quiet.
  if (!quiet && hide.length === 0 && unhide.length === 0 && !rename && !handleUri) openBrowser(targetPath);

  return { targetPath, sessionCount: sessions.length, skippedCount, hiddenCount: deduped.length - sessions.length };
}

