const HTML_ESCAPE_MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

function escapeHtml(str) {
  return String(str).replace(/[&<>"']/g, (ch) => HTML_ESCAPE_MAP[ch]);
}

function embedJsonSafely(data) {
  return JSON.stringify(data).replace(/[<>]/g, (ch) => (ch === '<' ? '\\u003c' : '\\u003e'));
}

function escapePowerShellSingleQuoted(str) {
  return String(str).replace(/'/g, "''");
}

function buildResumeCommand(tool, cwd, sessionId) {
  const cmd = tool === 'codex' ? 'codex resume' : 'claude --resume';
  const safeCwd = escapePowerShellSingleQuoted(cwd);
  return `Set-Location -LiteralPath '${safeCwd}'; ${cmd} ${sessionId}`;
}

// Used only by the sessdash://resume protocol action (see docs/design/2026-08-05-protocol-
// handler-resume-action.md) — deliberately a separate function from buildResumeCommand rather
// than reusing it verbatim. buildResumeCommand is the already-shipped, already-reviewed function
// behind the "copy resume command" clipboard button; that context is always a human pasting into
// an already-open terminal, so a Set-Location failure being a non-terminating error (the resume
// command still runs, from an unknown inherited directory) has never mattered there. Triggered
// via the protocol handler, nobody is watching that step happen — -ErrorAction Stop turns it into
// a terminating error so the resume command never runs from the wrong directory.
function buildResumeCommandForProtocol(tool, cwd, sessionId) {
  const cmd = tool === 'codex' ? 'codex resume' : 'claude --resume';
  const safeCwd = escapePowerShellSingleQuoted(cwd);
  return `Set-Location -LiteralPath '${safeCwd}' -ErrorAction Stop; ${cmd} ${sessionId}`;
}

function collectFlagPairs(argv, flag) {
  const pairs = [];
  for (let i = 0; i < argv.length; i++) {
    // Malformed --hide/--unhide (missing tool/id) can't happen in practice — the copied
    // command is always machine-generated by the dashboard's own hide button, never
    // hand-typed — so an incomplete trailing pair is simply skipped rather than raising
    // a usage error.
    if (argv[i] === flag && argv[i + 1] && argv[i + 2]) {
      pairs.push({ tool: argv[i + 1], id: argv[i + 2] });
    }
  }
  return pairs;
}

// --rename takes a third argument (the new title) that's arbitrary user-typed text — unlike
// tool/id it can contain spaces, so it arrives as its own argv element only because the copied
// PowerShell command single-quotes it (see buildRenameCmd in buildHtml). One rename per
// invocation is enough: unlike hide, the UI action that produces this command only ever
// targets one session at a time (a prompt() dialog on one card), so there's no batch case to
// support.
function parseRenameArg(argv) {
  const i = argv.indexOf('--rename');
  if (i === -1 || !argv[i + 1] || !argv[i + 2] || typeof argv[i + 3] !== 'string') return null;
  return { tool: argv[i + 1], id: argv[i + 2], title: argv[i + 3] };
}

// --handle-uri takes one argument: the full sessdash://... URI as invoked by Windows' protocol
// dispatch (the registered command passes the clicked link verbatim as "%1"). Shape/token
// validation happens later in handleProtocolUri, not here — parseArgs only extracts the raw
// string.
function parseHandleUriArg(argv) {
  const i = argv.indexOf('--handle-uri');
  if (i === -1 || typeof argv[i + 1] !== 'string') return null;
  return argv[i + 1];
}

function parseArgs(argv) {
  return {
    quiet: argv.includes('--quiet'),
    // Batch hide/unhide: the copied command may repeat --hide <tool> <id> multiple times
    // (one combined PowerShell invocation hiding several sessions at once) instead of
    // requiring one paste-and-run per session.
    hide: collectFlagPairs(argv, '--hide'),
    unhide: collectFlagPairs(argv, '--unhide'),
    rename: parseRenameArg(argv),
    handleUri: parseHandleUriArg(argv),
    registerProtocol: argv.includes('--register-protocol'),
    unregisterProtocol: argv.includes('--unregister-protocol'),
  };
}

// ---------------------------------------------------------------------------
// Deduplication
// ---------------------------------------------------------------------------
//
// Claude Code stores a session's jsonl file keyed by the project folder it was
// CURRENTLY running from. When a project folder is moved or copied to a new
// location and the same session is resumed from there, Claude Code writes a
// fresh copy of that session's jsonl file under the new project folder — the
// old copy is left in place, not cleaned up. Confirmed on real data: the same
// session id can physically exist as 2-3 separate files under different
// ~/.claude/projects/<encoded-path>/ folders, each scanned as its own card.
// Collapse entries sharing the same (tool, id) down to one, keeping the copy
// with the latest lastActiveAt (mtime) — on real duplicate files, the
// newest-mtime copy was also the most complete one (more lines), since that's
// the location the session kept being used from.

function dedupeSessions(sessions) {
  const byKey = new Map();
  for (const session of sessions) {
    const key = `${session.tool}:${session.id}`;
    const existing = byKey.get(key);
    if (!existing || new Date(session.lastActiveAt) > new Date(existing.lastActiveAt)) {
      byKey.set(key, session);
    }
  }
  return Array.from(byKey.values());
}

// ---------------------------------------------------------------------------
// Hidden-session list
// ---------------------------------------------------------------------------
//
// A user-facing "hide this session" action can't write to disk itself — buildHtml's output
// is a plain static file with no server, and a browser can't write arbitrary files. So hiding
// works the same way the existing "複製續接指令" button already does: copy a small CLI command
// to the clipboard, the user pastes it into a terminal, and *that* process (this same script,
// re-invoked with --hide) is what actually writes the change. This list only ever affects what
// this dashboard displays — it never touches the real .jsonl session files.

const HIDDEN_LIST_FILENAME = 'session-dashboard-hidden.json';

function loadHiddenList(filePath) {
  if (!fs.existsSync(filePath)) return [];
  try {
    const parsed = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    return Array.isArray(parsed) ? parsed : [];
  } catch (err) {
    // Malformed/corrupted list file — treat as empty rather than crashing dashboard
    // generation entirely; worst case a previously-hidden session becomes visible again.
    return [];
  }
}

function saveHiddenList(filePath, list) {
  writeAtomic(filePath, JSON.stringify(list));
}

function hideSession(filePath, tool, id) {
  const list = loadHiddenList(filePath);
  if (!list.some((entry) => entry.tool === tool && entry.id === id)) {
    list.push({ tool, id });
    saveHiddenList(filePath, list);
  }
}

function unhideSession(filePath, tool, id) {
  const list = loadHiddenList(filePath);
  const next = list.filter((entry) => !(entry.tool === tool && entry.id === id));
  if (next.length !== list.length) saveHiddenList(filePath, next);
}

function filterHiddenSessions(sessions, hiddenList) {
  const hiddenKeys = new Set(hiddenList.map((entry) => `${entry.tool}:${entry.id}`));
  return sessions.filter((s) => !hiddenKeys.has(`${s.tool}:${s.id}`));
}

// ---------------------------------------------------------------------------
// Rename a session
// ---------------------------------------------------------------------------
//
// Unlike hiding (which only ever touches our own session-dashboard-hidden.json), renaming
// writes directly into the tool's OWN session data so its own UI (e.g. Claude Code's built-in
// /resume picker) also shows the new name — the same "copy a CLI command, run it in a
// terminal" indirection as --hide, because a static HTML page still can't write files itself.
//
// Claude Code: confirmed by inspecting real data that `/rename` has no separate title index —
// the new name is recorded as one line appended to the session's OWN transcript jsonl:
// {type: "system", subtype: "local_command", content: "<command-name>/rename</command-name>...
// <command-args>NEW NAME</command-args>"}. This mirrors that exact real shape (see
// extractClaudeRenameTitle in adapters/claude-code.js, which is what reads it back), threading
// parentUuid/cwd from the file's own last record so it appends into the same uuid chain instead
// of looking like a disconnected root record.
//
// Codex: already has an official index file (session_index.jsonl, id -> thread_name) that our
// own reader already prefers (loadCodexIndex in adapters/codex.js) — renaming here is just
// appending {id, thread_name} to that same file. loadCodexIndex builds its map by iterating
// lines in file order and calling `.set(id, thread_name)`, so a later line for the same id
// naturally wins — no read-modify-write of the existing file is needed.

// A moved/copied project folder can leave the same session id living in more than one file
// under ~/.claude/projects/ (confirmed real case, see dedupeSessions above and deploy-log.md).
// dedupeSessions picks the copy with the newest scanned lastActiveAt to show on screen, so
// renaming has to resolve to that SAME copy — picking an arbitrary "first found" file could
// silently write to a stale duplicate the user never sees, making the rename look like it did
// nothing. A corrupted candidate is skipped (scanClaudeCodeFile throwing is the same signal
// scanClaudeCode's batch scan already treats as "unusable file, not a hard failure") rather than
// failing the whole lookup; the tie-break (strict >, keep the earliest-seen on an exact tie)
// mirrors dedupeSessions exactly so the two functions can never disagree about which copy is
// "the" copy. The common case (one match) never pays the extra scanClaudeCodeFile cost.
function findClaudeSessionFilePath(claudeHomeDir, id) {
  const candidates = walkJsonlFiles(path.join(claudeHomeDir, 'projects'), ['subagents']).filter(
    (f) => path.basename(f, '.jsonl') === id
  );
  if (candidates.length === 0) return null;
  if (candidates.length === 1) return candidates[0];
  let best = null;
  let bestTime = -Infinity;
  for (const candidate of candidates) {
    let session;
    try {
      session = scanClaudeCodeFile(candidate, os.homedir());
    } catch (err) {
      continue; // unusable duplicate — skip, don't let it fail the whole lookup
    }
    const t = new Date(session.lastActiveAt).getTime();
    if (best === null || t > bestTime) {
      best = candidate;
      bestTime = t;
    }
  }
  return best;
}

function renameClaudeSession(claudeHomeDir, id, newTitle) {
  const filePath = findClaudeSessionFilePath(claudeHomeDir, id);
  if (!filePath) throw new Error(`claude-code session not found: ${id}`);
  const tail = readLastJsonLines(filePath, 1);
  const lastRecord = tail[tail.length - 1] || {};
  const record = {
    parentUuid: typeof lastRecord.uuid === 'string' ? lastRecord.uuid : null,
    isSidechain: false,
    type: 'system',
    subtype: 'local_command',
    content:
      '<command-name>/rename</command-name>\n            <command-message>rename</command-message>\n            <command-args>' +
      String(newTitle) +
      '</command-args>',
    level: 'info',
    timestamp: new Date().toISOString(),
    uuid: crypto.randomUUID(),
    isMeta: false,
    userType: 'external',
    entrypoint: 'cli',
    cwd: typeof lastRecord.cwd === 'string' ? lastRecord.cwd : undefined,
    sessionId: id,
  };
  fs.appendFileSync(filePath, JSON.stringify(record) + '\n', 'utf8');
}

function renameCodexSession(codexHomeDir, id, newTitle) {
  const indexPath = path.join(codexHomeDir, 'session_index.jsonl');
  // Unlike renameClaudeSession (whose target file is only ever found because it already
  // exists), codexHomeDir itself may not exist yet on a machine that's never had Codex write
  // anything there — appendFileSync does not create missing parent directories.
  fs.mkdirSync(codexHomeDir, { recursive: true });
  fs.appendFileSync(indexPath, JSON.stringify({ id, thread_name: String(newTitle) }) + '\n', 'utf8');
}

function renameSession(claudeHomeDir, codexHomeDir, tool, id, newTitle) {
  if (tool === 'codex') renameCodexSession(codexHomeDir, id, newTitle);
  else renameClaudeSession(claudeHomeDir, id, newTitle);
}

// ---------------------------------------------------------------------------
// Protocol handler (sessdash://) — see docs/design/2026-08-04-protocol-handler-for-hide-rename.md
// ---------------------------------------------------------------------------
//
// Lets the hide/rename buttons trigger a real write without the manual copy-command-paste-into-
// terminal step, via a custom OS-registered URL protocol instead of a persistent local server.
// A registered protocol is system-wide (any webpage, not just our own dashboard, can construct
// a sessdash:// link), so every piece here is written defensively: strict allowlist validation
// before ever touching the token file, a registry ownership marker so register/unregister never
// touch a foreign registration, and atomic token publication so concurrent first-launches can't
// diverge.

const PROTOCOL_TOKEN_FILENAME = 'session-dashboard-token';
const PROTOCOL_LOG_FILENAME = 'session-dashboard-protocol.log';

// Write-to-unique-tempfile-then-linkSync gives real atomic "create if absent, otherwise tell me
// who won" semantics: linkSync either succeeds (we won) or fails with EEXIST (someone else won),
// and because the tempfile is fully written before the link ever exists, no reader can ever
// observe a partially-written token — unlike `{flag:'wx'}` alone, which only prevents two
// writers from both succeeding, not a reader catching a write-in-progress.
function loadOrCreateProtocolToken(filePath) {
  const dir = path.dirname(filePath);
  fs.mkdirSync(dir, { recursive: true });
  const tempPath = path.join(dir, `.session-dashboard-token.${process.pid}-${crypto.randomBytes(4).toString('hex')}.tmp`);
  const token = crypto.randomBytes(16).toString('hex');
  fs.writeFileSync(tempPath, token, 'utf8');
  try {
    fs.linkSync(tempPath, filePath);
  } catch (err) {
    if (err.code !== 'EEXIST') throw err;
  } finally {
    fs.unlinkSync(tempPath);
  }
  return fs.readFileSync(filePath, 'utf8').trim();
}

// Read-only counterpart used exclusively by --handle-uri's validation pipeline: returns null
// instead of creating anything. An untrusted external request that fails validation must never
// have the side effect of creating local state (e.g. "conjuring" a token file into existence on
// a machine where the dashboard was never actually generated).
function loadProtocolTokenIfExists(filePath) {
  if (!fs.existsSync(filePath)) return null;
  const token = fs.readFileSync(filePath, 'utf8').trim();
  return token || null;
}

function appendProtocolLog(logPath, message) {
  try {
    fs.mkdirSync(path.dirname(logPath), { recursive: true });
    fs.appendFileSync(logPath, `[${new Date().toISOString()}] ${message}\n`, 'utf8');
  } catch (err) {
    // Best-effort logging only — a failure to log must never mask or replace the original error.
  }
}

const PROTOCOL_SCHEME = 'sessdash:';
const PROTOCOL_ACTIONS = ['hide', 'rename', 'resume'];
const PROTOCOL_TOOLS = ['claude-code', 'codex'];

// Only the resume action needs this — hide/rename only ever use id to compare filenames or write
// it as JSON field content, never to build a string that gets executed. resume's id ends up
// inside a PowerShell command line, so it's held to a stricter allowlist: real ids are UUID-
// shaped (first character always a hex digit), and requiring the first character be alphanumeric
// specifically rules out an id starting with '-' being misread as a CLI flag by the downstream
// claude/codex command (e.g. an id of "--help") rather than a positional session id.
const SAFE_RESUME_ID_PATTERN = /^[A-Za-z0-9][A-Za-z0-9_-]*$/;

// Everything except the token comparison — kept pure (no filesystem access) so a malformed or
// out-of-allowlist request can be rejected before loadProtocolTokenIfExists is ever called.
// Stricter than renameSession's own internal "anything non-codex defaults to claude-code"
// looseness on purpose: that looseness is fine for internally-generated, trusted CLI flags, but
// this input can originate from any webpage's constructed link, so it's held to an exact
// allowlist instead.
function parseAndValidateProtocolUri(uriString) {
  let parsed;
  try {
    parsed = new URL(uriString);
  } catch (err) {
    return { ok: false, reason: `malformed URI: ${uriString}` };
  }
  if (parsed.protocol !== PROTOCOL_SCHEME) {
    return { ok: false, reason: `unexpected protocol: ${parsed.protocol}` };
  }
  if (!PROTOCOL_ACTIONS.includes(parsed.hostname)) {
    return { ok: false, reason: `unknown action: ${parsed.hostname}` };
  }

  function singleParam(name) {
    const all = parsed.searchParams.getAll(name);
    return all.length === 1 && all[0] ? all[0] : null;
  }

  const tool = singleParam('tool');
  const id = singleParam('id');
  if (!tool || !id) return { ok: false, reason: 'missing or duplicated tool/id parameter' };
  if (!PROTOCOL_TOOLS.includes(tool)) return { ok: false, reason: `unknown tool: ${tool}` };

  let title = null;
  if (parsed.hostname === 'rename') {
    title = singleParam('title');
    if (!title) return { ok: false, reason: 'missing or duplicated title parameter' };
  }

  let cwd = null;
  if (parsed.hostname === 'resume') {
    if (!SAFE_RESUME_ID_PATTERN.test(id)) return { ok: false, reason: `id contains characters outside the safe allowlist for resume: ${id}` };
    cwd = singleParam('cwd');
    if (!cwd) return { ok: false, reason: 'missing or duplicated cwd parameter' };
  }

  return { ok: true, action: parsed.hostname, tool, id, title, cwd, token: singleParam('token') };
}

// Opens a real, visible, interactive terminal — unlike hide/rename, which silently write a file
// and exit. See docs/design/2026-08-05-protocol-handler-resume-action.md for the empirical
// investigation behind this exact shape: a direct spawn('powershell.exe', ...) reliably dies
// within seconds without ever running the command (stdio:'ignore' — and the default 'pipe' —
// both leave PowerShell reading from a closed/EOF stdin, which no -NoExit can rescue); routing
// through `cmd.exe /c start` fixes that, but cmd.exe expands a defined environment variable
// (e.g. %USERNAME%) embedded anywhere in the command string, even when passed via Node's argv
// array — so the command is passed as -EncodedCommand (UTF-16LE base64) instead of -Command:
// base64 contains none of cmd.exe's special characters, so there is nothing left for that layer
// to reinterpret.
function resumeSession(tool, id, cwd, spawnFn, logPath) {
  const command = buildResumeCommandForProtocol(tool, cwd, id);
  const encodedCommand = Buffer.from(command, 'utf16le').toString('base64');
  const child = spawnFn('cmd.exe', ['/c', 'start', '""', 'powershell.exe', '-NoExit', '-EncodedCommand', encodedCommand], {
    detached: true,
    stdio: 'ignore',
    windowsHide: false,
  });
  // Best-effort only — see "殘留、刻意接受的限制" in the design doc: if this --handle-uri
  // one-shot process has already exited by the time an async spawn error fires (realistically
  // only if cmd.exe/powershell.exe itself can't be resolved), this log line never happens.
  child.on('error', (err) => {
    appendProtocolLog(logPath, `resume spawn failed: ${err.message}`);
  });
  child.unref();
}

// The full --handle-uri pipeline: shape validation (no side effects on failure) → token
// comparison (read-only lookup, never creates a token) → dispatch to the existing hide/rename
// write functions. Any rejection at any stage takes the same single path: log (token value
// itself is never logged — it's a bearer credential) then throw, so there's never a partially-
// applied state.
function handleProtocolUri(uriString, deps) {
  const { claudeHomeDir, codexHomeDir, hiddenListPath, tokenPath, logPath, spawnFn } = deps;
  const parsedResult = parseAndValidateProtocolUri(uriString);
  if (!parsedResult.ok) {
    appendProtocolLog(logPath, `rejected: ${parsedResult.reason}`);
    throw new Error(`protocol URI rejected: ${parsedResult.reason}`);
  }
  const expectedToken = loadProtocolTokenIfExists(tokenPath);
  if (!expectedToken || parsedResult.token !== expectedToken) {
    appendProtocolLog(
      logPath,
      'rejected: token mismatch (stale dashboard tab, dashboard never generated, or a link not from this dashboard)'
    );
    throw new Error('protocol URI rejected: token mismatch');
  }
  if (parsedResult.action === 'rename') {
    renameSession(claudeHomeDir, codexHomeDir, parsedResult.tool, parsedResult.id, parsedResult.title);
  } else if (parsedResult.action === 'resume') {
    resumeSession(parsedResult.tool, parsedResult.id, parsedResult.cwd, spawnFn || spawn, logPath);
  } else {
    hideSession(hiddenListPath, parsedResult.tool, parsedResult.id);
  }
}

// ---------------------------------------------------------------------------
// Protocol registration (--register-protocol / --unregister-protocol)
// ---------------------------------------------------------------------------

const PROTOCOL_ROOT_KEY = 'HKCU\\Software\\Classes\\sessdash';
const PROTOCOL_COMMAND_KEY = `${PROTOCOL_ROOT_KEY}\\shell\\open\\command`;
const PROTOCOL_OWNER_MARKER_VALUE = 'SessionDashboardOwner';
const PROTOCOL_OWNER_MARKER_CONTENT = 'session-dashboard-tool-v1';

function buildCanonicalCommandValue(scriptPath) {
  return `"${process.execPath}" "${scriptPath}" --handle-uri "%1"`;
}

// Existence is all we ever need to know here — never the value's actual content — so this never
// has to parse reg.exe's text output (which would be a locale-dependent, fragile thing to rely
// on). `reg query`'s non-zero exit on "not found" is its normal, expected way of reporting
// absence, NOT a real failure — deliberately not reusing the "any non-zero throws" contract that
// the real mutating reg add/reg delete calls rely on below.
function regExists(execFn, args) {
  try {
    execFn('reg', ['query', ...args]);
    return true;
  } catch (err) {
    return false;
  }
}

function isProtocolOwnedByUs(execFn) {
  return regExists(execFn, [PROTOCOL_ROOT_KEY, '/v', PROTOCOL_OWNER_MARKER_VALUE]);
}

// Ownership is decided SOLELY by the marker value (an arbitrary, entirely-our-own literal with
// no variable/path content) rather than comparing the functional values themselves — comparing
// the command value (which embeds process.execPath, expected to drift across Node
// upgrades/reinstalls) would force an impossible choice between tolerating that drift and being
// spoofable by a crafted foreign command string. The marker sidesteps that entirely: once it's
// present, we unconditionally refresh/complete the three functional values regardless of their
// individual current state — including a half-finished state left by an interrupted prior run,
// since ownership alone (not "are all values fully consistent") is what makes overwriting safe.
// The marker is written FIRST, before any functional value, so that recovery window is as wide
// as possible: interrupted after the marker write, the next run still recognizes and completes
// its own state; interrupted before it, nothing has happened yet.
function registerProtocolHandler(execFn, scriptPath) {
  const rootExists = regExists(execFn, [PROTOCOL_ROOT_KEY]);
  if (rootExists && !isProtocolOwnedByUs(execFn)) {
    throw new Error(
      `refusing to register: registry key "${PROTOCOL_ROOT_KEY}" already exists and has no ` +
        `"${PROTOCOL_OWNER_MARKER_VALUE}" marker — it doesn't look like ours, so it won't be overwritten. ` +
        'Please check it manually before proceeding.'
    );
  }
  execFn('reg', ['add', PROTOCOL_ROOT_KEY, '/v', PROTOCOL_OWNER_MARKER_VALUE, '/d', PROTOCOL_OWNER_MARKER_CONTENT, '/f']);
  execFn('reg', ['add', PROTOCOL_ROOT_KEY, '/ve', '/d', 'URL:Session Dashboard Protocol', '/f']);
  execFn('reg', ['add', PROTOCOL_ROOT_KEY, '/v', 'URL Protocol', '/d', '', '/f']);
  execFn('reg', ['add', PROTOCOL_COMMAND_KEY, '/ve', '/d', buildCanonicalCommandValue(scriptPath), '/f']);
}

function unregisterProtocolHandler(execFn) {
  const rootExists = regExists(execFn, [PROTOCOL_ROOT_KEY]);
  if (!rootExists) return; // already unregistered — safe no-op
  if (!isProtocolOwnedByUs(execFn)) {
    throw new Error(
      `refusing to unregister: registry key "${PROTOCOL_ROOT_KEY}" exists but has no ` +
        `"${PROTOCOL_OWNER_MARKER_VALUE}" marker — it doesn't look like ours, so it won't be deleted. ` +
        'Please check it manually before proceeding.'
    );
  }
  execFn('reg', ['delete', PROTOCOL_ROOT_KEY, '/f']);
}

function defaultExecProtocolCommand(command, args) {
  execFileSync(command, args, { stdio: 'ignore' });
}

