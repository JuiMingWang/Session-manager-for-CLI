// Hidden-session list
// ---------------------------------------------------------------------------
//
// A user-facing "hide this session" action can't write to disk itself — buildHtml's output
// is a plain static file with no server, and a browser can't write arbitrary files. So hiding
// works the same way the existing "複製續接指令" button already does: copy a small CLI command
// to the clipboard, the user pastes it into a terminal, and *that* process (this same script,
// re-invoked with --hide) is what actually writes the change. This list only ever affects what
// this dashboard displays — it never touches the real .jsonl session files.

const HIDDEN_LIST_FILENAME = 'session-dashboard-hidden.json';

function loadHiddenList(filePath) {
  if (!fs.existsSync(filePath)) return [];
  try {
    const parsed = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    return Array.isArray(parsed) ? parsed : [];
  } catch (err) {
    // Malformed/corrupted list file — treat as empty rather than crashing dashboard
    // generation entirely; worst case a previously-hidden session becomes visible again.
    return [];
  }
}

