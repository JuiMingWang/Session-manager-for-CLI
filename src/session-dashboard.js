      // 只有 13 行的自動化稽核任務跟一筆 7 行的廢棄殼子落在同一群），所以刻意不自動
      // 隱藏，只集中列出讓使用者自己一眼判斷、視需要手動隱藏——跟久未使用整理區同一
      //套「集中但不搬移、不刪除」的做法。
